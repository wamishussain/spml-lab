def log_fit_stats(x, y):
    x = np.asarray(x)
    y = np.asarray(y)

    mask = (x > 0) & (y > 0)
    x = x[mask]
    y = y[mask]

    lx = np.log(x)
    ly = np.log(y)

    slope, intercept = np.polyfit(lx, ly, 1)
    pred = intercept + slope * lx

    ss_res = np.sum((ly - pred)**2)
    ss_tot = np.sum((ly - np.mean(ly))**2)

    r2 = 1 - ss_res / ss_tot
    corr = np.corrcoef(lx, ly)[0, 1]

    return slope, intercept, r2, corr


def bootstrap_r2_comparison(risk, chi, chi_weighted, n_boot=500, seed=123):
    rng = np.random.default_rng(seed)

    risk = np.asarray(risk)
    chi = np.asarray(chi)
    chi_weighted = np.asarray(chi_weighted)

    mask = (risk > 0) & (chi > 0) & (chi_weighted > 0)
    risk = risk[mask]
    chi = chi[mask]
    chi_weighted = chi_weighted[mask]

    N = len(risk)

    r2_unweighted = np.zeros(n_boot)
    r2_weighted = np.zeros(n_boot)
    delta_r2 = np.zeros(n_boot)

    for b in range(n_boot):
        idx = rng.integers(0, N, size=N)

        _, _, r2_u, _ = log_fit_stats(chi[idx], risk[idx])
        _, _, r2_w, _ = log_fit_stats(chi_weighted[idx], risk[idx])

        r2_unweighted[b] = r2_u
        r2_weighted[b] = r2_w
        delta_r2[b] = r2_w - r2_u

    return {
        "r2_unweighted_boot": r2_unweighted,
        "r2_weighted_boot": r2_weighted,
        "delta_r2_boot": delta_r2,
        "delta_r2_mean": float(np.mean(delta_r2)),
        "delta_r2_ci_low": float(np.percentile(delta_r2, 2.5)),
        "delta_r2_ci_high": float(np.percentile(delta_r2, 97.5)),
        "prob_delta_positive": float(np.mean(delta_r2 > 0)),
    }


