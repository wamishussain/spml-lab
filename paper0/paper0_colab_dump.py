import numpy as np

def ridge_risk_exact(n, d, sigma=0.3, lam=1e-8, seed=0):
    # Random number generator
    rng = np.random.default_rng(seed)

    # True teacher vector theta_*
    theta = rng.normal(size=d)
    theta = theta / np.linalg.norm(theta)

    # Training data X
    X = rng.normal(size=(n, d))

    # Noise epsilon
    eps = sigma * rng.normal(size=n)

    # Labels y = X theta_* + epsilon
    y = X @ theta + eps

    # Ridge solution
    if d <= n:
        A = X.T @ X / n
        b = X.T @ y / n
        theta_hat = np.linalg.solve(A + lam * np.eye(d), b)
    else:
        K = X @ X.T / n
        alpha = np.linalg.solve(K + lam * np.eye(n), y / n)
        theta_hat = X.T @ alpha

    # Exact isotropic population test risk
    risk = np.sum((theta_hat - theta) ** 2)

    return risk

