import numpy as np

def ridge_diagnostics(n, d, sigma=0.3, lam=1e-8, seed=0):
    rng = np.random.default_rng(seed)

    theta = rng.normal(size=d)
    theta = theta / np.linalg.norm(theta)

    X = rng.normal(size=(n, d))
    eps = sigma * rng.normal(size=n)
    y = X @ theta + eps

    if d <= n:
        A = X.T @ X / n
        b = X.T @ y / n
        theta_hat = np.linalg.solve(A + lam * np.eye(d), b)

        eig = np.linalg.eigvalsh(A)
        eig = eig[eig > 1e-14]
    else:
        K = X @ X.T / n
        alpha = np.linalg.solve(K + lam * np.eye(n), y / n)
        theta_hat = X.T @ alpha

        eig = np.linalg.eigvalsh(K)
        eig = eig[eig > 1e-14]

    risk = np.sum((theta_hat - theta) ** 2)
    lambda_min = np.min(eig)
    chi = np.sum(eig / (eig + lam)**2) / n

    return risk, lambda_min, chi


