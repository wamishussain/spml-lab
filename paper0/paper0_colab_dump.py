def ridge_experiment(n, d, lam=1e-8, n_seeds=20, n_test=500, sigma_noise=0.3):
    risks = np.zeros(n_seeds)
    kappas = np.zeros(n_seeds)
    lmins = np.zeros(n_seeds)
    chis = np.zeros(n_seeds)

    for seed in range(n_seeds):
        rng = np.random.default_rng(seed)

        theta = rng.normal(size=d)
        theta /= np.linalg.norm(theta)

        X = rng.normal(size=(n, d))
        eps = sigma_noise * rng.normal(size=n)
        y = X @ theta + eps

        sv = np.linalg.svd(X, compute_uv=False)
        eig_pos = sv**2 / n

        kappas[seed] = sv[0] / (sv[-1] + 1e-15)
        lmins[seed] = eig_pos[-1]
        chis[seed] = np.sum(eig_pos / (eig_pos + lam)**2) / n

        if d <= n:
            A = X.T @ X / n
            b = X.T @ y / n
            theta_hat = np.linalg.solve(A + lam * np.eye(d), b)
        else:
            K = X @ X.T / n
            alpha = np.linalg.solve(K + lam * np.eye(n), y / n)
            theta_hat = X.T @ alpha

        Xt = rng.normal(size=(n_test, d))
        risks[seed] = np.mean((Xt @ theta_hat - Xt @ theta)**2)

    return risks, kappas, lmins, chis


