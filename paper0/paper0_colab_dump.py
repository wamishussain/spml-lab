def binned_log_plot(x, y, nbins=12, min_count=8):
    x = np.asarray(x)
    y = np.asarray(y)

    mask = (x > 0) & (y > 0)
    x = x[mask]
    y = y[mask]

    bins = np.logspace(np.log10(x.min()), np.log10(x.max()), nbins + 1)

    xb, ymed, ylo, yhi = [], [], [], []

    for i in range(nbins):
        m = (x >= bins[i]) & (x < bins[i+1])
        if np.sum(m) < min_count:
            continue

        xb.append(np.sqrt(bins[i] * bins[i+1]))
        ymed.append(np.median(y[m]))
        ylo.append(np.percentile(y[m], 25))
        yhi.append(np.percentile(y[m], 75))

    return np.array(xb), np.array(ymed), np.array(ylo), np.array(yhi)


