def run_seeds_diag_cov(
    n,
    d,
    variances,
    n_seeds=200,
    sigma=0.3,
    lam=1e-8,
):
    """
    Linear ridge with diagonal population covariance Sigma.

    X = Z Sigma^{1/2}

    Exact population test risk:
        risk = (theta_hat - theta)^T Sigma (theta_hat - theta)

    Susceptibilities:
        chi_unweighted = (1/n) sum_k eig_k / (eig_k + lam)^2

        chi_weighted = (1/n) sum_k (v_k^T Sigma v_k)
                       eig_k / (eig_k + lam)^2

    where v_k are right singular vectors of X.
    """

    variances = np.asarray(variances)
    scales = np.sqrt(variances)

    risks = np.zeros(n_seeds)
    kappas = np.zeros(n_seeds)
    lmins = np.zeros(n_seeds)
    chi_unweighted = np.zeros(n_seeds)
    chi_weighted = np.zeros(n_seeds)

    for s in range(n_seeds):
        rng = np.random.default_rng(s)

        theta = rng.normal(size=d)
        theta /= np.linalg.norm(theta)

        Z = rng.normal(size=(n, d))
        X = Z * scales[None, :]

        eps = sigma * rng.normal(size=n)
        y = X @ theta + eps

        # Full SVD is needed for right singular vectors.
        U, sv, Vt = np.linalg.svd(X, full_matrices=False)
        eig = sv**2 / n

        kappas[s] = sv[0] / (sv[-1] + 1e-15)
        lmins[s] = eig[-1]

        # v_k^T Sigma v_k for each right singular vector v_k.
        sigma_weights = np.sum((Vt**2) * variances[None, :], axis=1)

        chi_unweighted[s] = np.sum(eig / (eig + lam)**2) / n
        chi_weighted[s] = np.sum(sigma_weights * eig / (eig + lam)**2) / n

        A = X.T @ X / n
        b = X.T @ y / n
        theta_hat = np.linalg.solve(A + lam * np.eye(d), b)

        diff = theta_hat - theta

        # Exact population test risk under x ~ N(0, Sigma)
        risks[s] = np.sum(variances * diff**2)

    return risks, kappas, lmins, chi_unweighted, chi_weighted

def log_fit_stats(x, y):
    """
    Fit log y = intercept + slope log x.
    Return slope, intercept, R^2, correlation.
    """
    x = np.asarray(x)
    y = np.asarray(y)

    mask = (x > 0) & (y > 0)
    x = x[mask]
    y = y[mask]

    lx = np.log(x)
    ly = np.log(y)

    slope, intercept = np.polyfit(lx, ly, 1)
    pred = intercept + slope * lx

    ss_res = np.sum((ly - pred)**2)
    ss_tot = np.sum((ly - np.mean(ly))**2)

    r2 = 1.0 - ss_res / ss_tot
    corr = np.corrcoef(lx, ly)[0, 1]

    return slope, intercept, r2, corr


def bootstrap_r2_comparison(risk, chi, chi_weighted, n_boot=500, seed=123):
    """
    Bootstrap pooled R^2 difference:
        Delta R^2 = R^2_weighted - R^2_unweighted
    """
    rng = np.random.default_rng(seed)

    risk = np.asarray(risk)
    chi = np.asarray(chi)
    chi_weighted = np.asarray(chi_weighted)

    mask = (risk > 0) & (chi > 0) & (chi_weighted > 0)
    risk = risk[mask]
    chi = chi[mask]
    chi_weighted = chi_weighted[mask]

    N = len(risk)

    r2_unweighted = np.zeros(n_boot)
    r2_weighted = np.zeros(n_boot)
    delta_r2 = np.zeros(n_boot)

    slope_unweighted = np.zeros(n_boot)
    slope_weighted = np.zeros(n_boot)

    for b in range(n_boot):
        idx = rng.integers(0, N, size=N)

        slope_u, _, r2_u, _ = log_fit_stats(chi[idx], risk[idx])
        slope_w, _, r2_w, _ = log_fit_stats(chi_weighted[idx], risk[idx])

        slope_unweighted[b] = slope_u
        slope_weighted[b] = slope_w
        r2_unweighted[b] = r2_u
        r2_weighted[b] = r2_w
        delta_r2[b] = r2_w - r2_u

    return {
        "r2_unweighted_boot": r2_unweighted,
        "r2_weighted_boot": r2_weighted,
        "delta_r2_boot": delta_r2,
        "slope_unweighted_boot": slope_unweighted,
        "slope_weighted_boot": slope_weighted,
        "delta_r2_mean": float(np.mean(delta_r2)),
        "delta_r2_ci_low": float(np.percentile(delta_r2, 2.5)),
        "delta_r2_ci_high": float(np.percentile(delta_r2, 97.5)),
        "prob_delta_positive": float(np.mean(delta_r2 > 0)),
    }

