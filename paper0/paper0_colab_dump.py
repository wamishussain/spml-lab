def ridge_one_trial(n, d, sigma=0.3, lam=1e-8, seed=0):
    rng = np.random.default_rng(seed)

    theta = rng.normal(size=d)
    theta /= np.linalg.norm(theta)

    X = rng.normal(size=(n, d))
    eps = sigma * rng.normal(size=n)
    y = X @ theta + eps

    if d <= n:
        A = X.T @ X / n
        b = X.T @ y / n
        theta_hat = np.linalg.solve(A + lam * np.eye(d), b)
    else:
        K = X @ X.T / n
        alpha = np.linalg.solve(K + lam * np.eye(n), y / n)
        theta_hat = X.T @ alpha

    risk = np.sum((theta_hat - theta) ** 2)
    return risk

