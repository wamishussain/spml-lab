def run_seeds_diag_cov(
    n,
    d,
    variances,
    n_seeds=300,
    sigma=0.3,
    lam=1e-8
):
    """
    Linear ridge with diagonal population covariance Sigma.

    X = Z Sigma^{1/2}
    Test risk computed exactly:
        risk = (theta_hat - theta)^T Sigma (theta_hat - theta)

    Observables:
        lmin          = smallest eigenvalue of X^T X/n
        chi_unweighted = (1/n) sum eig/(eig+lam)^2
        chi_weighted   = (1/n) sum (v_k^T Sigma v_k) eig/(eig+lam)^2
    """

    variances = np.asarray(variances)
    scales = np.sqrt(variances)

    risks = np.zeros(n_seeds)
    kappas = np.zeros(n_seeds)
    lmins = np.zeros(n_seeds)
    chi_unweighted = np.zeros(n_seeds)
    chi_weighted = np.zeros(n_seeds)

    for s in range(n_seeds):
        rng = np.random.default_rng(s)

        theta = rng.normal(size=d)
        theta /= np.linalg.norm(theta)

        Z = rng.normal(size=(n, d))
        X = Z * scales[None, :]

        eps = sigma * rng.normal(size=n)
        y = X @ theta + eps

        # Full SVD gives right singular vectors.
        U, sv, Vt = np.linalg.svd(X, full_matrices=False)
        eig = sv**2 / n

        kappas[s] = sv[0] / (sv[-1] + 1e-15)
        lmins[s] = eig[-1]

        weights_sigma = np.sum((Vt**2) * variances[None, :], axis=1)

        chi_unweighted[s] = np.sum(eig / (eig + lam)**2) / n
        chi_weighted[s] = np.sum(weights_sigma * eig / (eig + lam)**2) / n

        if d <= n:
            A = X.T @ X / n
            b = X.T @ y / n
            theta_hat = np.linalg.solve(A + lam * np.eye(d), b)
        else:
            K = X @ X.T / n
            alpha = np.linalg.solve(K + lam * np.eye(n), y / n)
            theta_hat = X.T @ alpha

        diff = theta_hat - theta

        # Exact population test risk under x ~ N(0, Sigma)
        risks[s] = np.sum(variances * diff**2)

    return risks, kappas, lmins, chi_unweighted, chi_weighted

